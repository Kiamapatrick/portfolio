    /* ── SMOOTH_TAU for velocity smoothing (from original) ── */
    const SMOOTH_TAU = 0.25;

    /* ── Build one LogoLoop instance ────────────────────────── */
    function buildLoop(container, logos) {
        const speed = parseFloat(container.dataset.speed || '80');
        const direction = container.dataset.direction || 'left';
        const hoverSpeed = container.dataset.hoverSpeed !== undefined
            ? parseFloat(container.dataset.hoverSpeed) : undefined;

        /* Direction multiplier: left = positive offset (moves left) */
        const dirMult = direction === 'left' ? 1 : -1;
        const targetVel = speed * dirMult;

        /* Build the track with 4 copies so we always fill the viewport */
        const track = document.createElement('div');
        track.className = 'logoloop__track';

        const COPIES = 6;
        for (let c = 0; c < COPIES; c++) {
            const ul = document.createElement('ul');
            ul.className = 'logoloop__list';
            ul.setAttribute('role', 'list');
            if (c > 0) ul.setAttribute('aria-hidden', 'true');

            logos.forEach((item, i) => {
                const li = document.createElement('li');
                li.className = 'logoloop__item';
                li.setAttribute('role', 'listitem');

                const node = document.createElement('span');
                node.className = 'logoloop__node';
                node.style.color = item.color || 'currentColor';
                node.innerHTML = item.svg;
                node.title = item.title || '';

                li.appendChild(node);
                ul.appendChild(li);
            });

            track.appendChild(ul);
        }

        container.appendChild(track);

        /* ── Animation state ────── */
        let offsetPx = 0;
        let velocity = targetVel;
        let lastTs = null;
        let seqWidth = 0;
        let isHovered = false;
        let raf = null;

        /* Measure the first list width after paint.
           On mobile the container is inside overflow:hidden so
           getBoundingClientRect() can return 0 on the first frame.
           Fall back to scrollWidth and retry with backoff. */
        function measureSeq() {
            const firstList = track.querySelector('.logoloop__list');
            if (!firstList) return;
            const r = firstList.getBoundingClientRect().width;
            const s = firstList.scrollWidth;
            seqWidth = r > 0 ? r : (s > 0 ? s : 0);
        }

        let _retries = 0;
        function measureWithRetry() {
            measureSeq();
            if (seqWidth <= 0 && _retries < 20) {
                _retries++;
                setTimeout(measureWithRetry, 50 * _retries);
            } else if (!raf) {
                raf = requestAnimationFrame(animate);
            }
        }

        requestAnimationFrame(() => {
            measureSeq();
            if (seqWidth > 0) {
                raf = requestAnimationFrame(animate);
            } else {
                measureWithRetry();
            }
        });

        new ResizeObserver(() => {
            measureSeq();
            if (!raf) raf = requestAnimationFrame(animate);
        }).observe(container);

        function animate(ts) {
            if (!lastTs) { lastTs = ts; }
            const dt = Math.min((ts - lastTs) / 1000, 0.1); // cap delta
            lastTs = ts;

            /* Smooth velocity towards target */
            const target = (isHovered && hoverSpeed !== undefined) ? hoverSpeed : targetVel;
            const ease = 1 - Math.exp(-dt / SMOOTH_TAU);
            velocity += (target - velocity) * ease;

            if (seqWidth > 0) {
                offsetPx = ((offsetPx + velocity * dt) % seqWidth + seqWidth) % seqWidth;
                track.style.transform = `translate3d(${-offsetPx}px, 0, 0)`;
            }

            raf = requestAnimationFrame(animate);
        }

        /* Pause / slow on hover */
        if (hoverSpeed !== undefined) {
            track.addEventListener('mouseenter', () => { isHovered = true; });
            track.addEventListener('mouseleave', () => { isHovered = false; });
        }

        /* Pause when tab hidden */
        document.addEventListener('visibilitychange', () => {
            if (document.hidden) {
                cancelAnimationFrame(raf);
                raf = null;
                lastTs = null;
            } else {
                if (!raf) raf = requestAnimationFrame(animate);
            }
        });
    }

    /* ── Init all .logoloop containers ─────────────────────── */
    document.addEventListener('DOMContentLoaded', () => {
        const containers = document.querySelectorAll('.logoloop[data-row]');
        containers.forEach(c => {
            const row = parseInt(c.dataset.row, 10);
            const logos = row === 2 ? ROW_2 : ROW_1;
            buildLoop(c, logos);
        });
    });

